AXES = ("x", "y", "z")

# the unit of the stresses of the units of lengths and forces (#132)
STRESS = {("mm", "N"): "MPa", ("mm", "kN"): "GPa", ("m", "N"): "Pa", ("m", "kN"): "kPa"}

# the fields of the displacements by the type of the analysis of a model (#175)
FIELDS = {
    "3d": ("fem.Field", 3, None),
    "plane-strain": ("fem.FieldPlaneStrain", 2, "planestrain=True"),
    "axisymmetric": ("fem.FieldAxisymmetric", 2, "axisymmetric=True"),
}

# the comments of the type of the analysis of a 2D model (#175)
ANALYSES = {
    "axisymmetric": (
        "# axisymmetric: x is the axis of rotation, y the radius; the forces are the"
        "\n# totals over the circumference\n"
    ),
    "plane-strain": (
        "# plane strain in the xy-plane: the forces are per unit thickness in z\n"
    ),
}


def unit(quantity, units):
    """Return the unit of a quantity (``length``, ``force`` or ``stress``) of the
    units of the model settings, or None.

    Examples
    --------
    >>> unit("stress", {"length": "mm", "force": "N"})
    'MPa'
    >>> unit("length", None) is None
    True
    """
    if not units or quantity is None:
        return None
    if quantity == "stress":
        return STRESS[units["length"], units["force"]]
    return units[quantity]


def parameter_value(parameter):
    """Return the value of a parameter of the model: an int for an integer parameter,
    else a float.

    Examples
    --------
    >>> parameter_value({"name": "layers", "value": 3.0, "integer": True})
    3
    """
    if parameter.get("integer"):
        return int(parameter["value"])
    return float(parameter["value"])


def parameter_line(parameter, units=None):
    """Return the line of a parameter of the model in the script: a float, or an int
    for an integer parameter, with its unit as a comment (#180).

    Examples
    --------
    >>> parameter_line({"name": "radius", "value": 50, "quantity": "length"},
    ...                {"length": "mm", "force": "N"})
    'radius = 50.0  # mm'
    >>> parameter_line({"name": "layers", "value": 3.0, "integer": True})
    'layers = 3'
    """
    code = getattr(parameter["value"], "code", None)
    if code is None:
        line = f"{parameter['name']} = {parameter_value(parameter)!r}"
    else:
        # a derived parameter (ADR 0021): its expression, without the parentheses
        # of a field, an integer one as an int like in the app
        expression = code[1:-1] if code.startswith("(") else code
        if parameter.get("integer"):
            expression = f"int({expression})"
        line = f"{parameter['name']} = {expression}"
    suffix = unit(parameter.get("quantity"), units)
    return f"{line}  # {suffix}" if suffix else line


def derived(parameter):
    """Whether a parameter of a resolved command list is a derived parameter (ADR
    0021): its value knows its expression."""
    return hasattr(parameter["value"], "text")


def parameter_order(parameters):
    """Return the parameters in the order of the script: the free ones in the order
    of the command list, then the derived ones in the order of their evaluation
    (ADR 0021), each after the derived parameters that it uses."""
    free = [p for p in parameters if not derived(p)]
    pending = [p for p in parameters if derived(p)]
    ordered = []
    while pending:
        later = {p["name"] for p in pending}
        first = next(
            (p for p in pending if not set(names(p["value"].text)) & later),
            pending[0],
        )
        pending.remove(first)
        ordered.append(first)
    return free + ordered


class Context:
    """The commands of a script and the values that several of its parts use (ADR
    0018), computed once.

    Parameters
    ----------
    commands : list of dict
        The resolved commands of the command list (ADR 0013).
    evaluate : bool, optional
        Evaluate the jobs at the end of the script (default is True).
    """

    def __init__(self, commands, evaluate=True):
        self.commands = commands
        self.evaluate = evaluate
        settings = self.get("model.settings")
        settings = settings[0] if settings else {}
        self.units = settings.get("units")
        # a 2D model (#175): fields of two components, plane strain or axisymmetric
        self.analysis = analysis_of(commands)
        self.field_class, self.dim, self.mixed_flag = FIELDS[self.analysis]
        self.axes = AXES[: self.dim]
        # a model in single precision (ADR 0016, #297): the regions and the fields
        self.single = settings.get("precision") == "single"
        self.astype = ".astype(DTYPE)" if self.single else ""
        self.dtype = ["dtype=DTYPE"] if self.single else []

    def get(self, *kinds):
        """Return the commands of these types, in their order."""
        return [c for c in self.commands if c["command"] in kinds]

    def emit(self, emitters, comment=None):
        """Return the lines of the commands of the types of a registry of emitters,
        in the order of the commands, after a comment if there are any."""
        commands = self.get(*emitters)
        if not commands:
            return []
        lines = [f"\n{comment}"] if comment else []
        for command in commands:
            lines.extend(emitters[command["command"]](self, command))
        return lines

    def container(self, name, region):
        """Return the line of a field container of a field of the displacements of a
        region."""
        field = wrap(self.field_class, [region, f"dim={self.dim}", *self.dtype])
        return call(name, "fem.FieldContainer", [f"[{field}]"])

    def components(self, vector, name):
        """Return the components of a vector of a point set (a force, or of a
        rotation point in a 2D model a moment about z)."""
        if self.dim == 2 and name in self.rotations:
            return [vector[2], 0]
        return vector[: self.dim]

    @cached_property
    def parameters(self):
        return self.get("parameter.add")

    @cached_property
    def sections(self):
        return self.get("section.add")

    @cached_property
    def solids(self):
        """The names of the solid bodies of the sections."""
        return [f"solid_{sec['name']}" for sec in self.sections]

    @cached_property
    def volumes(self):
        """Whether the steps leave out the solid bodies of sections without volume
        when the script runs (#429): of a model with meshes of scripts, which may make
        an empty part as one degenerate cell (#418)."""
        return bool(self.get("mesh.script"))

    @cached_property
    def material_kinds(self):
        """The kinds of the user-defined materials (ADR 0025), e.g. ``hyperelastic``
        of a strain energy function of a file (#424) or ``strain`` of a strain-based
        function (#425)."""
        return {m["kind"] for m in self.get("material.script")}

    @cached_property
    def section_helpers(self):
        """The blocks of the helpers of the fields and the solid bodies of the
        sections (ADR 0024), e.g. ``mixed`` of mixed fields."""
        return sections.helpers(self.sections)

    @cached_property
    def controls(self):
        """The control points and the reference points of the rigid surfaces (#219)."""
        return self.get("point.add", "rigid.add")

    @cached_property
    def rigids(self):
        return {r["name"]: r for r in self.get("rigid.add")}

    @cached_property
    def pointsets(self):
        """The point sets, with the control points and the reference points of the
        rigid surfaces (a point set of one point each, #219)."""
        return self.get("pointset.add", "point.add", "rigid.add")

    @cached_property
    def surface_points(self):
        """Whether a point set has the points on the surface (#222)."""
        pointsets = self.get("pointset.add")
        return any("surface" in ps.get("select", {}) for ps in pointsets)

    @cached_property
    def needs_solid_points(self):
        """Whether the point sets need the points of the cells of the sections: for
        the bounds (#181) and the points of contacts (#220)."""
        names = {ps["name"] for ps in self.get("pointset.add")}
        contacts = any(c["points"] in names for c in self.get("contact.add"))
        bounds = any("bound" in ps.get("select", {}) for ps in self.get("pointset.add"))
        return contacts or bounds

    @cached_property
    def facesets(self):
        return self.get("faceset.add")

    @cached_property
    def faceset_names(self):
        return {fs["name"] for fs in self.facesets}

    @cached_property
    def loadcases(self):
        return {lc["name"]: lc for lc in self.get("loadcase.add")}

    @cached_property
    def symmetries(self):
        return self.get("symmetry.add")

    @cached_property
    def constraints(self):
        """The multi-point constraints and the Cartesian and cylindrical constraints
        (#421, #422)."""
        return self.get("mpc.add", "cartesian.add", "cylindrical.add")

    @cached_property
    def moved(self):
        """The constraints in local coordinates by their names, which a step ramps
        and which may be the curve of a job: the Cartesian and the cylindrical
        constraints (#421, #422)."""
        return {c["name"]: c for c in self.get(*MOVED)}

    @cached_property
    def dimensions(self):
        """The dimensions of the meshes made by tools (ADR 0019)."""
        return meshtools.dimensions(self.commands)

    @cached_property
    def tag_names(self):
        """The names of the cell tags of the meshes with cell tags, also of those
        made by tools (#438)."""
        return meshtools.tag_names(self.commands)

    @cached_property
    def rotations(self):
        """The rotation points of the constraints: in a 2D model (#175), the rotation
        about z is the first component of a rotation point (FElupe locks the second
        one)."""
        return {c["rotation"] for c in self.constraints if "rotation" in c}

    @cached_property
    def loads(self):
        return {load["name"]: load for load in self.get("load.add")}

    @cached_property
    def pressures(self):
        return {p["name"]: p for p in self.get("pressure.add")}


def header(context):
    """The part of the header: the imports and the comments of the model settings,
    and ``DTYPE`` of a model in single precision."""
    # meshio only in scripts that read mesh files or run mesh scripts, not in those
    # whose meshes are made by tools (ADR 0019); PARDISO only in scripts with a job
    # that uses it (#308)
    files = context.get("mesh.import") or context.get("mesh.script")
    pardiso = jobs.uses_pardiso(context.get("job.add"))
    # functools only in scripts with the Mullins effect of a material of tensortrax
    # (#346), also of a strain energy function of a file (#424)
    partial = uses_functools(context.get("material.add", "material.script"))
    lines = [
        HEADER.format(
            version=__version__,
            schema=SCHEMA_VERSION,
            stdlib="import functools\n\n" if partial else "",
            meshio="import meshio\n" if files else "",
            imports="import pypardiso\n" if pardiso else "",
        )
    ]
    if context.units:
        # FElupe has no units: the settings only say what the numbers mean (#132)
        units = context.units
        stress = STRESS[units["length"], units["force"]]
        lines.append(
            f"# units: {units['length']} (lengths), {units['force']} (forces) and "
            f"{stress} (stresses); FElupe does not convert them\n"
        )
    if context.analysis in ANALYSES:
        lines.append(ANALYSES[context.analysis])
    if context.single:
        lines.append(
            "# single precision: the regions, the fields and the linear equation "
            "system in\n# float32, half the memory of double precision\n"
            "DTYPE = np.float32\n"
        )
    return lines


def parameters(context):
    """The part of the parameters of the model, at the top to be changed by hand
    (#180)."""
    if not context.parameters:
        return []
    lines = [
        parameter_line(p, context.units) for p in parameter_order(context.parameters)
    ]
    return ["\n".join(["# parameters", *lines]) + "\n"]


def helpers(context):
    """The part of the helpers that the script needs."""
    blocks = [BLOCKS[key] for key, needed in HELPERS if needed(context)]
    return [blocks[0], *(f"\n{block}" for block in blocks[1:])]


# the parts of a script, in this order (ADR 0018)
PARTS = (
    header,
    parameters,
    helpers,
    sections.meshes,
    sections.materials,
    sections.sections,
    sets.pointsets,
    sets.facesets,
    sets.loadcases,
    sets.boundaries,
    items.constraints,
    items.cartesians,
    items.cylindricals,
    items.contacts,
    items.loads,
    items.pressures,
    jobs.steps,
    jobs.jobs,
)


def codegen(document, evaluate=True, check_schema=True):
    """Return the FElupe script of a command list as a string.

    Parameters
    ----------
    document : dict
        The command list ``{"schema_version": 1, "commands": [...]}``. It is
        validated first, see :func:`felupe_studio.commands.validate`.
    evaluate : bool, optional
        Evaluate the jobs at the end of the script (default is True).
    check_schema : bool, optional
        Validate the command list against the JSON schema (default is True). The
        references between the commands are checked in any case.

    Returns
    -------
    str
        The FElupe script.
    """
    validate(document, check_schema)
    # the values of the expressions of the parameters (#242), shown as written
    context = Context(resolve(document)[0]["commands"], evaluate)
    if context.pointsets and not context.sections:
        raise ValidationError(["Point sets need at least one section (a field)."])
    lines = [line for part in PARTS for line in part(context)]
    return dedent("\n".join(lines)).strip() + "\n"
