"""Turn a command list into a readable FElupe script (ADR 0003).

The generated script only needs FElupe, NumPy and meshio (and tensortrax for the
hyperelastic models of tensortrax, e.g. Mooney-Rivlin), so an exported script runs
outside of FElupe Studio as well. Its structure is fixed and independent of the order
of the commands:

1. meshes and cell sets
2. materials
3. a region and a field container per section, merged into the top-level field
4. solid bodies (created after the merge, see :func:`felupe.field.merge`)
5. point sets, load cases (``fem.dof``) and boundaries on the merged field
6. steps and jobs
"""

import ast
import json
from importlib.resources import files
from textwrap import dedent

from .__about__ import __version__
from .commands import SCHEMA_VERSION, ValidationError, validate
from .loadcases import loadcase_call, moving
from .materials import material_call

HEADER = '''\
"""FElupe script generated by FElupe Studio {version} (command schema {schema})."""

from types import SimpleNamespace

import felupe as fem
import meshio
import numpy as np
'''

MARKER = "# --- embedded in generated scripts ---\n"
HELPERS = files("felupe_studio").joinpath("_helpers.py").read_text(encoding="utf-8")
HELPERS = HELPERS[HELPERS.index(MARKER) + len(MARKER) :]

AXES = ("x", "y", "z")

# the unit of the stresses of the units of lengths and forces (#132)
STRESS = {("mm", "N"): "MPa", ("mm", "kN"): "GPa", ("m", "N"): "Pa", ("m", "kN"): "kPa"}


LINE_LENGTH = 88


def _str(value):
    """Python string literal with double quotes."""
    return json.dumps(value, ensure_ascii=False)


class _List:
    """A list argument ``prefix[item, ...]`` that ruff format may explode."""

    def __init__(self, items, prefix=""):
        self.items = list(items)
        self.prefix = prefix

    def __str__(self):
        return f"{self.prefix}[{', '.join(self.items)}]"

    def exploded(self, level):
        pad = "    " * level
        items = "".join(f"{pad}    {item},\n" for item in self.items)
        return f"{self.prefix}[\n{items}{pad}]"


class _Dict:
    """A dict argument ``prefix{key: value, ...}`` that ruff format may explode."""

    def __init__(self, items, prefix=""):
        self.items = list(items)
        self.prefix = prefix

    def __str__(self):
        return f"{self.prefix}{{{', '.join(self.items)}}}"

    def exploded(self, level):
        pad = "    " * level
        items = "".join(f"{pad}    {item},\n" for item in self.items)
        return f"{self.prefix}{{\n{items}{pad}}}"


class _Call:
    """A call argument ``func(arg, ...)`` that ruff format may explode."""

    def __init__(self, func, args):
        self.func = func
        self.args = list(args)

    def __str__(self):
        return f"{self.func}({', '.join(self.args)})"

    def exploded(self, level):
        pad = "    " * level
        inner = f"{pad}    {', '.join(self.args)}"
        if len(inner) <= LINE_LENGTH:
            return f"{self.func}(\n{inner}\n{pad})"
        args = "".join(f"{pad}    {arg},\n" for arg in self.args)
        return f"{self.func}(\n{args}{pad})"


def _explode(args, level=1):
    """One argument per line with a trailing comma, like ruff format."""
    pad = "    " * level
    lines = []
    for arg in args:
        line = f"{pad}{arg},"
        if len(line) > LINE_LENGTH and isinstance(arg, (_List, _Dict, _Call)):
            line = f"{pad}{arg.exploded(level)},"
        lines.append(line + "\n")
    return "".join(lines)


def _wrap(head, args, level=0, end=""):
    """A call ``head(args)``, wrapped like ruff format would wrap it."""
    pad = "    " * level
    line = f"{pad}{head}({', '.join(map(str, args))}){end}"
    if len(line) <= LINE_LENGTH:
        return line
    inner = f"{pad}    " + ", ".join(map(str, args))
    if len(inner) <= LINE_LENGTH:
        return f"{pad}{head}(\n{inner}\n{pad}){end}"
    if len(args) == 1 and isinstance(args[0], _List):
        return f"{pad}{head}(\n{pad}    {args[0].exploded(level + 1)}\n{pad}){end}"
    return f"{pad}{head}(\n{_explode(args, level + 1)}{pad}){end}"


def _call(target, func, args):
    """Assignment of a call, wrapped like ruff format would wrap it."""
    return _wrap(f"{target} = {func}", args)


def evaluate_options(job):
    """Return the keyword arguments of ``Job.evaluate()`` of a ``job.add`` command,
    besides ``x0``: the settings of the Newton-Raphson method that are given.

    Examples
    --------
    >>> evaluate_options({"name": "job_1", "steps": ["step_1"], "tol": 0.05})
    {'tol': 0.05}
    >>> evaluate_options({"name": "job_1", "steps": ["step_1"], "maxiter": 30})
    {'maxiter': 30}
    """
    options = {}
    if "tol" in job:
        options["tol"] = float(job["tol"])
    if "maxiter" in job:
        options["maxiter"] = int(job["maxiter"])
    return options


# the parameters of fem.CutbackPlugin of the settings of a cutback (#133)
CUTBACK = {"factor": float, "max_cutbacks": int, "growth": float}


def cutback_options(job):
    """Return the keyword arguments of ``fem.CutbackPlugin`` of a ``job.add`` command
    with a cutback, the parameters that are given (``None`` without a cutback).

    Examples
    --------
    >>> cutback_options({"cutback": {"factor": 0.25}})
    {'factor': 0.25}
    >>> cutback_options({"cutback": {}})
    {}
    >>> cutback_options({}) is None
    True
    """
    if "cutback" not in job:
        return None
    cutback = job["cutback"]
    return {key: kind(cutback[key]) for key, kind in CUTBACK.items() if key in cutback}


def codegen(document, evaluate=True, check_schema=True):
    """Return the FElupe script of a command list as a string.

    Parameters
    ----------
    document : dict
        The command list ``{"schema_version": 1, "commands": [...]}``. It is
        validated first, see :func:`felupe_studio.commands.validate`.
    evaluate : bool, optional
        Evaluate the jobs at the end of the script (default is True).
    check_schema : bool, optional
        Validate the command list against the JSON schema (default is True). The
        references between the commands are checked in any case.

    Returns
    -------
    str
        The FElupe script.
    """
    validate(document, check_schema)
    commands = document["commands"]

    def get(command):
        return [c for c in commands if c["command"] == command]

    sections = get("section.add")
    # point sets, with the control points (a point set of one point each)
    pointsets = [c for c in commands if c["command"] in ("pointset.add", "point.add")]
    if pointsets and not sections:
        raise ValidationError(["Point sets need at least one section (a field)."])

    out = [HEADER.format(version=__version__, schema=SCHEMA_VERSION)]
    settings = get("model.settings")
    units = settings[0].get("units") if settings else None
    if units:
        # FElupe has no units: the settings only say what the numbers mean (#132)
        stress = STRESS[units["length"], units["force"]]
        out.append(
            f"# units: {units['length']} (lengths), {units['force']} (forces) and "
            f"{stress} (stresses); FElupe does not convert them\n"
        )
    out.append(HELPERS)

    # 1. meshes and cell sets
    meshes = get("mesh.import")
    if meshes:
        out.append("\n# meshes")
        for mesh in meshes:
            args = [f"meshio.read({_str(mesh['file'])})"]
            for key in ("tag", "cell_type"):
                if key in mesh:
                    args.append(f"{key}={_str(mesh[key])}")
            out.append(_call(mesh["name"], "volume_cells", args))

    cellsets = [c for c in commands if c["command"].startswith("cellset.")]
    if cellsets:
        out.append("\n# cell sets")
        for cmd in cellsets:
            m = cmd["mesh"]
            cells = f"{m}.cells"
            if cmd["command"] == "cellset.from_tag":
                cells += f"[{m}.tags == {cmd['value']!r}]"
            args = [f"{m}.points", cells, f"{m}.cell_type"]
            out.append(_call(cmd["name"], "fem.Mesh", args))

    # 2. materials
    materials = get("material.add")
    if materials:
        out.append("\n# materials")
        for mat in materials:
            func, args, volumetric = material_call(mat)
            out.append(_call(mat["name"], func, args))
            if volumetric:
                out.append(_wrap(f"{mat['name']} &= fem.Volumetric", volumetric))

    # 3. fields of the sections, merged into the top-level field
    if sections:
        out.append("\n# sections: a region and a field container per section")
        for sec in sections:
            c = sec["cellset"]
            region = f"region_{sec['name']}"
            if sec["formulation"] == "u":
                out.append(_call(region, f"REGIONS[{c}.cell_type]", [c]))
            else:
                out.append(_call(region, "mixed_region", [c]))
            if sec["formulation"] == "u":
                fields = f"[fem.Field({region}, dim=3)]"
                out.append(
                    _call(f"field_{sec['name']}", "fem.FieldContainer", [fields])
                )
            else:
                out.append(
                    _call(f"field_{sec['name']}", "fem.FieldsMixed", [region, "n=3"])
                )

        controls = get("point.add")
        if controls:
            out.append(
                "\n# control points: a mesh of vertices, not nodes of the sections"
            )
            coordinates = (
                f"[{', '.join(map(repr, p['coordinates']))}]" for p in controls
            )
            out.append(
                _call("region_control_points", "vertex_region", [_List(coordinates)])
            )
            fields = "[fem.Field(region_control_points, dim=3)]"
            out.append(_call("field_control_points", "fem.FieldContainer", [fields]))

        fields = _List(
            [f"field_{s['name']}" for s in sections]
            + (["field_control_points"] if controls else [])
        )
        out.append(
            "\n# merge the displacements of all sections into the top-level field"
        )
        merge = get("mesh.merge")
        args = [fields] + [f"decimals={m['decimals']!r}" for m in merge]
        out.append(_call("field", "fem.field.merge", args))

        # 4. solid bodies, after the merge
        out.append("\n# solid bodies")
        for sec in sections:
            umat = sec["material"]
            if sec["formulation"] == "u-p-J":
                args = [umat, f"bulk={sec['bulk']!r}"]
                # the volumetric part of the strain energy, if not the default (#134)
                volumetric = sec.get("volumetric", "volume-ratio")
                if volumetric != "volume-ratio":
                    args.append(f"volumetric={_str(volumetric)}")
                umat = _Call("fem.NearlyIncompressible", args)
            out.append(
                _call(
                    f"solid_{sec['name']}",
                    "fem.SolidBody",
                    [umat, f"field_{sec['name']}"],
                )
            )

    # 5. point sets, load cases (``fem.dof``) and boundaries on the merged field
    if pointsets:
        out.append("\n# point sets of the merged mesh")
        out.append("points = field.mesh_container.points")
        for ps in pointsets:
            if ps["command"] == "point.add":
                point = f"[{', '.join(map(repr, ps['coordinates']))}]"
                out.append(_call(ps["name"], "points_at", ["points", point]))
                continue
            sel = ps["select"]
            if "axis" in sel:
                axis = AXES.index(sel["axis"])
                args = [
                    f"points[:, {axis}]",
                    repr(sel["value"]),
                    f"atol={sel.get('atol', 1e-8)!r}",
                ]
                out.append(_call(ps["name"], "np.isclose", args))
            elif "points" in sel:
                coordinates = (f"[{', '.join(map(repr, p))}]" for p in sel["points"])
                args = ["points", _List(coordinates)]
                if "atol" in sel:
                    args.append(f"atol={sel['atol']!r}")
                out.append(_call(ps["name"], "points_at", args))
            else:
                out.append(_call(ps["name"], "np.zeros", ["len(points)", "dtype=bool"]))
                out.append(f"{ps['name']}[{sel['ids']!r}] = True")

    loadcases = {lc["name"]: lc for lc in get("loadcase.add")}
    if loadcases:
        out.append("\n# load cases (fem.dof), ramped by the steps")
        for lc in loadcases.values():
            func, args = loadcase_call(lc)
            out.append(_call(lc["name"], func, args))

    boundaries = get("boundary.add")
    out.append("\n# boundaries")
    if boundaries or loadcases:
        out.append("boundaries = {")
        for bc in boundaries:
            args = ["field[0]", f"mask={bc['pointset']}"]
            skip = tuple(0 if a in bc["constrained"] else 1 for a in AXES)
            if any(skip):
                args.append(f"skip={skip!r}")
            if bc.get("value", 0) != 0:
                args.append(f"value={bc['value']!r}")
            head = f"{_str(bc['name'])}: fem.Boundary"
            out.append(_wrap(head, args, level=1, end=","))
        for name in loadcases:
            out.append(f'    **{{f"{name}/{{k}}": v for k, v in {name}.items()}},')
        out.append("}")
    else:
        out.append("boundaries = {}")

    loads = {load["name"]: load for load in get("load.add")}

    def ramped(name, values):
        """Items of a ramp: a boundary, the moving boundaries of a load case, or a
        point load (its force, scaled by the values)."""
        if name in loads:
            force = f"[{', '.join(map(repr, loads[name]['force']))}]"
            return [f"{name}: np.outer({values}, {force})"]
        if name not in loadcases:
            return [f"boundaries[{_str(name)}]: {values}"]
        return [
            f"boundaries[{_str(name + '/' + key)}]: {'' if sign > 0 else '-'}{values}"
            for key, sign in moving(loadcases[name])
        ]

    def curve(name):
        """The boundary of a characteristic curve (of a load case: its first move), or
        a point load (the displacement of its first point over its total force)."""
        if name in loads:
            return name
        if name in loadcases:
            name = f"{name}/{moving(loadcases[name])[0][0]}"
        return f"boundaries[{_str(name)}]"

    constraints = get("mpc.add")
    if constraints:
        out.append("\n# multi-point constraints")
        for mpc in constraints:
            args = [
                "field",
                f"points=np.flatnonzero({mpc['points']})",
                f"centerpoint=single_point({mpc['center']}, {_str(mpc['center'])})",
            ]
            skip = tuple(a not in mpc["constrained"] for a in AXES)
            if any(skip):
                args.append(f"skip={skip!r}")
            if "multiplier" in mpc:
                args.append(f"multiplier={mpc['multiplier']!r}")
            if "rotation" in mpc:
                point = f"single_point({mpc['rotation']}, {_str(mpc['rotation'])})"
                args.append(f"rotationpoint={point}")
            out.append(_call(mpc["name"], "fem.MultiPointConstraint", args))

    if loads:
        out.append("\n# point loads: the force at every point, scaled by the ramps")
        for load in loads.values():
            force = f"[{', '.join(map(repr, load['force']))}]"
            args = ["field", f"points={load['points']}", f"values={force}"]
            out.append(_call(load["name"], "fem.PointLoad", args))

    # 6. steps and jobs
    steps = get("step.add")
    if steps:
        out.append("\n# steps")
        for step in steps:
            names = step.get("sections", [s["name"] for s in sections])
            items = (
                ["solid_" + n for n in names]
                + step.get("constraints", [c["name"] for c in constraints])
                + step.get("loads", list(loads))
            )
            lines = [_List(items, prefix="items=")]
            if "ramp" in step:
                r = step["ramp"]
                ramp = f"ramp_{step['name']}"
                num = f"num={r['num']!r}"

                def linsteps(item):
                    return f"[{item.get('start', 0)!r}, {item['end']!r}]"

                if len({linsteps(item) for item in r["items"]}) == 1:
                    # the same values for all items: one array
                    args = [linsteps(r["items"][0]), num]
                    out.append(_call(ramp, "fem.math.linsteps", args))
                    values = {item["target"]: ramp for item in r["items"]}
                else:
                    # an array per item, in the order of the items
                    out.append(f"{ramp} = [")
                    for item in r["items"]:
                        call = f"fem.math.linsteps({linsteps(item)}, {num})"
                        out.append(f"    {call},  # {item['target']}")
                    out.append("]")
                    values = {
                        item["target"]: f"{ramp}[{i}]"
                        for i, item in enumerate(r["items"])
                    }
                items = [
                    entry
                    for target, value in values.items()
                    for entry in ramped(target, value)
                ]
                lines.append(_Dict(items, prefix="ramp="))
            lines.append("boundaries=boundaries")
            out.append(f"{step['name']} = fem.Step(\n{_explode(lines)})")

    jobs = get("job.add")
    if jobs:
        out.append("\n# jobs")
        for job in jobs:
            args = [_List(job["steps"], prefix="steps=")]
            if "curve" in job:
                args.append(f"boundary={curve(job['curve'])}")
                if job["curve"] in loads:
                    # the force of a load: the sum of the internal forces at its points
                    reacting = [f"solid_{s['name']}" for s in sections]
                    reacting += [c["name"] for c in constraints]
                    args.append(_List(reacting, prefix="items="))
            cutback = cutback_options(job)
            if cutback is not None:
                options = ", ".join(f"{k}={v!r}" for k, v in cutback.items())
                args.append(f"plugins=[fem.CutbackPlugin({options})]")
            func = "fem.CharacteristicCurve" if "curve" in job else "fem.Job"
            out.append(_call(job["name"], func, args))
        if evaluate:
            out.append("")
            for job in jobs:
                args = ["x0=field"]
                args += [f"{k}={v!r}" for k, v in evaluate_options(job).items()]
                out.append(_wrap(f"{job['name']}.evaluate", args))

    return dedent("\n".join(out)).strip() + "\n"


def _names(node):
    """The names that an expression reads."""
    return {n.id for n in ast.walk(node) if isinstance(n, ast.Name)}


def object_lines(script, document):
    """Return the lines of a generated script that belong to the objects of the
    command list, for the script view of the app (#130).

    Parameters
    ----------
    script : str
        The script of :func:`codegen`.
    document : dict
        The command list of the script.

    Returns
    -------
    dict
        The ranges ``[first, last]`` of the lines (counted from 1) of every object
        with lines, e.g. ``{"rubber": [[30, 30]], "block": [[25, 25], [52, 57]]}``:
        its assignment, and the parts of other statements that are about it (an
        entry of the boundaries, the evaluation of a job). Lines that are about
        several objects (e.g. the merge of the fields) belong to none of them.
    """
    commands = document["commands"]
    names = {c["name"] for c in commands}
    kinds = {c["name"]: c["command"] for c in commands}
    controls = [c["name"] for c in commands if c["command"] == "point.add"]
    merge = [c["name"] for c in commands if c["command"] == "mesh.merge"]
    lines = {}

    def add(name, node):
        lines.setdefault(name, []).append([node.lineno, node.end_lineno])

    def owners(target):
        """The objects of an assigned name, e.g. a section of its solid body."""
        if target in names:
            return [target]
        if target in ("region_control_points", "field_control_points"):
            return controls
        if target == "field":
            return merge
        for prefix, kind in [
            ("region_", "section.add"),
            ("field_", "section.add"),
            ("solid_", "section.add"),
            ("ramp_", "step.add"),
        ]:
            name = target.removeprefix(prefix)
            if target.startswith(prefix) and kinds.get(name) == kind:
                return [name]
        return []

    # the comment of the units of the model settings (not in the syntax tree)
    settings = [c["name"] for c in commands if c["command"] == "model.settings"]
    for number, line in enumerate(script.splitlines(), start=1):
        if settings and line.startswith("# units: "):
            lines[settings[0]] = [[number, number]]

    for statement in ast.parse(script).body:
        if isinstance(statement, (ast.Assign, ast.AugAssign, ast.AnnAssign)):
            targets = (
                statement.targets
                if isinstance(statement, ast.Assign)
                else [statement.target]
            )
            for target in targets:
                if isinstance(target, ast.Subscript):
                    target = target.value  # e.g. the ids of a point set
                if not isinstance(target, ast.Name):
                    continue
                if target.id == "boundaries" and isinstance(statement.value, ast.Dict):
                    # an entry per boundary, and the boundaries of the load cases
                    entries = zip(
                        statement.value.keys, statement.value.values, strict=True
                    )
                    for key, value in entries:
                        if isinstance(key, ast.Constant) and key.value in names:
                            lines.setdefault(key.value, []).append(
                                [key.lineno, value.end_lineno]
                            )
                        elif key is None:
                            for name in sorted(_names(value) & names):
                                add(name, value)
                    continue
                for name in owners(target.id):
                    add(name, statement)
        elif isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Call):
            func = statement.value.func  # e.g. job.evaluate(...)
            if isinstance(func, ast.Attribute) and isinstance(func.value, ast.Name):
                if func.value.id in names:
                    add(func.value.id, statement)

    # sorted ranges, joined where they touch
    for name, ranges in lines.items():
        joined = []
        for first, last in sorted(ranges):
            if joined and first <= joined[-1][1] + 1:
                joined[-1][1] = max(joined[-1][1], last)
            else:
                joined.append([first, last])
        lines[name] = joined
    return lines
