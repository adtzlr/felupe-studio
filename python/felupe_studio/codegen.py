MARKER = "# --- embedded in generated scripts ---\n"


def _blocks(markers):
    """The blocks of the helpers that are embedded in generated scripts, by their
    markers in ``_helpers.py``."""
    text = files("felupe_studio").joinpath("_helpers.py").read_text(encoding="utf-8")
    text = text[text.index(MARKER) + len(MARKER) :]
    blocks = {}
    for key, marker in reversed(markers.items()):
        text, blocks[key] = text.split(marker)
    return {"all": text, **blocks}


